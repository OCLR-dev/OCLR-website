import { readFileSync, writeFileSync } from "node:fs";

const assets = new URL("../public/themes/orbital-pulse/", import.meta.url);
const body = (name: string) =>
  readFileSync(new URL(name, assets), "utf8")
    .replace(/^<svg\b[^>]*>\s*/, "")
    .replace(/\s*<\/svg>\s*$/, "");
const spectrum = body("music-spectrum.svg");

// Keep the original analysed spectrum and circuit primitives. Inline both so
// the SVG works as a CSS image without scripts or external image references.
for (const theme of ["light", "dark"] as const) {
  const field = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 240" fill="none">
<!-- Generated by scripts/generate-orbital-field.ts from the existing S6 assets. -->
<svg width="640" height="240" viewBox="800 0 640 240">
${body(`circuit-${theme}.svg`)}
</svg>
<svg x="160" y="30" width="320" height="180" viewBox="0 0 320 180">
${spectrum}
</svg>
</svg>
`;
  writeFileSync(new URL(`orbital-field-${theme}.svg`, assets), field);
}

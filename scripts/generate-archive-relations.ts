import { z } from "zod";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { format } from "prettier";
import { historicalArchiveSchema } from "../src/lib/historical-archive";
import { statisticsSnapshotSchema } from "../src/lib/statistics-snapshot";
import { archiveStatisticsSummarySchema } from "../src/lib/archive-summary-schema";
import type {
  Layout,
  Node,
  Entity,
  Scalar,
} from "../src/lib/archive-relational-codec";

type Schema = Record<string, unknown> & {
  type?: string;
  properties?: Record<string, Schema>;
  anyOf?: Schema[];
  oneOf?: Schema[];
  items?: Schema;
  prefixItems?: Schema[];
  additionalProperties?: Schema | boolean;
};
const snake = (s: string) =>
  s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const identifier = (s: string) =>
  s.length <= 60
    ? s
    : `${s.slice(0, 48)}_${createHash("sha256").update(s).digest("hex").slice(0, 10)}`;
function merge(s: Schema): Schema {
  if (Array.isArray(s.type)) {
    const types = s.type.filter((t) => t !== "null");
    return { ...s, type: types.length === 1 ? types[0] : "mixed" };
  }
  const variants = (s.anyOf ?? s.oneOf)
    ?.filter((v) => v.type !== "null")
    .map(merge);
  if (!variants) return s;
  if (variants.length === 1) return variants[0];
  if (variants.every((v) => v.type === "object"))
    return {
      type: "object",
      properties: Object.assign({}, ...variants.map((v) => v.properties)),
    };
  if (variants.every((v) => v.type === variants[0].type)) return variants[0];
  return { type: "mixed" };
}
const layouts: Layout[] = [];
for (const [kind, schema] of [
  ["archive", historicalArchiveSchema],
  ["statistics", statisticsSnapshotSchema],
  ["summary", archiveStatisticsSummarySchema],
] as const) {
  const entities: Entity[] = [];
  function entity(s: Schema, path: string[], parent?: string): string {
    const key = identifier(
      `archive_rel_${kind}${path.length ? `_${path.map(snake).join("_")}` : ""}`,
    );
    if (entities.some((e) => e.key === key))
      throw new Error(`Duplicate relation ${key}`);
    const e: Entity = {
      key,
      parent,
      fields: [],
      node: { type: "object", properties: {} },
    };
    entities.push(e);
    function node(input: Schema, fieldPath: string[]): Node {
      const s = merge(input);
      // Variants are a map keyed by difficulty configuration, not separate schemas.
      const dictionary =
        s.type === "object" &&
        (typeof s.additionalProperties === "object" ||
          fieldPath.at(-1) === "variants");
      if (dictionary) {
        const item =
          typeof s.additionalProperties === "object"
            ? s.additionalProperties
            : Object.values(s.properties ?? {})[0];
        if (!item) throw new Error(`Unknown dictionary ${path}.${fieldPath}`);
        return {
          type: "relation",
          mode: "record",
          entity: entity(item, [...path, ...fieldPath], key),
        };
      }
      if (s.type === "object")
        return {
          type: "object",
          properties: Object.fromEntries(
            Object.entries(s.properties ?? {}).map(([name, child]) => [
              name,
              node(child, [...fieldPath, name]),
            ]),
          ),
        };
      if (s.type === "array") {
        const items = s.prefixItems ?? (s.items ? [s.items] : []);
        if (!items.length)
          throw new Error(`Missing array schema ${path}.${fieldPath}`);
        const item = merge(items[0]);
        if (item.type === "object" || item.type === "array")
          return {
            type: "relation",
            mode: "array",
            entity: entity(item, [...path, ...fieldPath], key),
          };
        if (!items.every((v) => merge(v).type === item.type))
          throw new Error("Mixed tuple needs an explicit mapping");
        return scalar(item.type, fieldPath, true);
      }
      return scalar(s.type, fieldPath, false);
    }
    function scalar(
      type: string | undefined,
      path: string[],
      array: boolean,
    ): Node {
      if (
        !["string", "integer", "number", "boolean", "mixed"].includes(
          type ?? "",
        )
      )
        throw new Error(`Unsupported scalar ${type}`);
      if (array && type === "mixed")
        throw new Error("Unsupported mixed scalar array");
      const column = identifier(`value_${path.map(snake).join("_") || "item"}`);
      if (e.fields.some((f) => f.column === column))
        throw new Error(`Duplicate field ${key}.${column}`);
      e.fields.push({ column, type: type as Scalar, array });
      return { type: "scalar", column, scalar: type as Scalar, array };
    }
    e.node = node(s, []);
    return key;
  }
  const root = entity(z.toJSONSchema(schema) as Schema, []);
  layouts.push({ kind, root, entities });
}
const declarations = [
  "// Generated by scripts/generate-archive-relations.ts; do not edit.",
  'import { pgTable, uuid, integer, text, bigint, doublePrecision, boolean, primaryKey, foreignKey, index, unique, check } from "drizzle-orm/pg-core";',
  'import { sql } from "drizzle-orm";',
  'import { archiveRelationDocuments } from "./schema";',
];
const name = (key: string) =>
  key.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
for (const layout of layouts)
  for (const e of layout.entities) {
    const fields = e.fields.flatMap((f) => {
      const builder = (type: Scalar, column: string) =>
        `${type === "integer" ? `bigint(${JSON.stringify(column)}, {mode:"number"})` : `${{ string: "text", number: "doublePrecision", boolean: "boolean", mixed: "text" }[type]}(${JSON.stringify(column)})`}${f.array ? ".array()" : ""}`;
      if (f.type === "mixed")
        return [
          `${JSON.stringify(f.column + "_type")}: text(${JSON.stringify(f.column + "_type")}),`,
          ...(["string", "number", "boolean"] as const).map(
            (t) =>
              `${JSON.stringify(f.column + "_" + t)}: ${builder(t, f.column + "_" + t)},`,
          ),
        ];
      return [`${JSON.stringify(f.column)}: ${builder(f.type, f.column)},`];
    });
    declarations.push(`export const ${name(e.key)} = pgTable(${JSON.stringify(e.key)}, {
    documentId: uuid("document_id").notNull(),
    id: integer("id").notNull(), parentId: integer("parent_id")${e.parent ? ".notNull()" : ""}, position: integer("position").notNull(),
    recordKey: text("record_key"), present: text("present").array().notNull(), nulls: text("nulls").array().notNull(),
    ${fields.join("\n")}
  }, t=>[primaryKey({name:${JSON.stringify(identifier(e.key + "_pk"))},columns:[t.documentId,t.id]}), unique(${JSON.stringify(identifier(e.key + "_order_key"))}).on(t.documentId,t.parentId,t.position),
    foreignKey({name:${JSON.stringify(identifier(e.key + "_document_fk"))},columns:[t.documentId],foreignColumns:[archiveRelationDocuments.id]}),
    ${e.parent ? `foreignKey({name:${JSON.stringify(identifier(e.key + "_parent_fk"))},columns:[t.documentId,t.parentId], foreignColumns:[${name(e.parent)}.documentId,${name(e.parent)}.id]}),` : `check(${JSON.stringify(identifier(e.key + "_root"))},sql\`\${t.id}=0 AND \${t.parentId} IS NULL\`),`}
    ${e.fields
      .filter(
        (f) =>
          !f.array &&
          [
            "value_osu_id",
            "value_team_id",
            "value_beatmap_id",
            "value_slot",
          ].includes(f.column),
      )
      .map(
        (f) =>
          `index(${JSON.stringify(identifier(e.key + "_" + f.column + "_idx"))}).on(t[${JSON.stringify(f.column)}],t.documentId),`,
      )
      .join("\n")}
  ]);`);
  }
declarations.push(
  `export const archiveRelationTables = {${layouts
    .flatMap((l) => l.entities)
    .map((e) => `${JSON.stringify(e.key)}:${name(e.key)}`)
    .join(",")}};`,
);
const outputs = [
  ["src/lib/archive-relational-layout.json", JSON.stringify(layouts)],
  ["src/db/archive-relational-schema.ts", declarations.join("\n")],
] as const;
for (const [file, source] of outputs) {
  const output = await format(source, {
    parser: file.endsWith("json") ? "json" : "typescript",
  });
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== output)
      throw new Error(
        `Regenerate ${file} with npm run archive:relations:generate`,
      );
  } else writeFileSync(file, output);
}
console.log(
  `${layouts.flatMap((l) => l.entities).length} typed historical relations synchronized.`,
);
